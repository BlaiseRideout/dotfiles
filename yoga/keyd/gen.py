#!/usr/bin/env python3
"""Generate yoga-bt-kb.conf (the keyd config for the Yoga Book's Bluetooth keyboard).

    python3 yoga/keyd/gen.py > yoga/keyd/yoga-bt-kb.conf

It is generated because every mod-tap key needs a small "quick-tap" layer of its own
(see the header written below), which is too repetitive to keep by hand. The mod-tap
tables and timings are the single source here.
"""

# ZMK hold-tap terms in ms. Shift is 125 in the ZMK keymap, raised for false holds.
T = {"shift": 160, "control": 165, "alt": 165, "meta": 200}
QUICK_TAP_MS = 165  # keyd has one global oneshot timeout; ZMK's quick-tap-ms is 125..200
# keyd allows 32 layers/sections per config, so only these NUM mod-taps get a quick-tap
# layer (the digits); the symbols on the top row are plain mod-taps.
NUM_QT = ["a", "s", "d", "f", "j", "k", "l", "semicolon"]

# key: modifier layer, in the order of the ZMK keymap (top row, then home row).
MODS = {
    "q": "alt", "w": "meta", "e": "control", "r": "shift",
    "u": "shift", "i": "control", "o": "meta", "p": "alt",
    "a": "meta", "s": "alt", "d": "shift", "f": "control",
    "j": "control", "k": "shift", "l": "alt", "semicolon": "meta",
}
# What those keys type on the ZMK NUM_LAYER (tap); the same keys hold the same mods.
NUM_TAP = {
    "q": "S-1", "w": "S-2", "e": "S-3", "r": "S-4",
    "u": "S-7", "i": "S-8", "o": "S-9", "p": "S-0",
    "a": "1", "s": "2", "d": "3", "f": "4",
    "j": "7", "k": "8", "l": "9", "semicolon": "0",
}
# NUM keys without a mod
NUM_PLAIN = [
    ("t", "S-5"), ("y", "S-6"), ("leftbrace", "equal"),
    ("g", "5"), ("h", "6"), ("apostrophe", "minus"),
    ("z", "grave"), ("x", "S-grave"), ("c", "e"), ("v", "S-minus"), ("b", "S-equal"),
    ("n", "S-z"), ("m", "rightbrace"), ("comma", "S-rightbrace"),
    ("dot", "S-backslash"), ("slash", "backslash"),
]
NAV = [
    ("r", "playpause"), ("y", "pageup"), ("u", "home"), ("i", "up"), ("o", "end"),
    ("p", "sysrq"), ("leftbrace", "f12"),
    ("h", "pagedown"), ("j", "left"), ("k", "down"), ("l", "up"),
    ("semicolon", "right"), ("apostrophe", "enter"),
    ("z", "previoussong"), ("x", "nextsong"), ("c", "volumedown"), ("v", "volumeup"),
    ("b", "playpause"), ("n", "C-tab"), ("m", "C-S-tab"), ("comma", "C-tab"),
    ("dot", "S-insert"),
]

out = []
w = out.append
w(f"""\
# GENERATED by yoga/keyd/gen.py (edit that, then: python3 yoga/keyd/gen.py > yoga/keyd/yoga-bt-kb.conf).
#
# Home row mods on the Yoga Book 9i's Bluetooth keyboard, ported from the BASE layer
# of BlaiseRideout/zmk-configs (link/link.keymap). Installed to /etc/keyd/ by
# ansible/yoga.yaml; notes in docs/yoga-book/homerow-mods.md.
#
# keyd works on physical keys, so these sit on the same positions as in the ZMK
# keymap whatever the OS layout is (hyprland.lua uses us/dvorak).
#
# overloadt(layer, key, ms) = ZMK's tap-preferred hold-tap: a hold only if the key is
# still down after ms (other keys are queued until then or until release), otherwise
# a tap. Timings are the ZMK ones except shift, raised from 125 to {T['shift']}ms (false
# holds): shift {T['shift']}ms, alt/ctrl {T['control']}ms, gui {T['meta']}ms.
#
# Quick-tap (ZMK's quick-tap-ms): tap a mod-tap key and press it again within
# {QUICK_TAP_MS}ms and the second press is the plain key, so holding it repeats the
# letter instead of turning into a modifier. keyd has no such option, so a tap also
# switches on a one-shot layer (qt_<key>; qtn_<key> for the NUM digits only, as keyd
# allows 32 layers) that binds just that key to itself; keyd's oneshot_timeout ends
# it, and any other typed key ends it too.
#
# Layers: holding space gives NUM (numbers and symbols), holding capslock gives NAV
# (arrows, paging, media), both from the ZMK keymap's NUM_LAYER and NAV_LAYER (which
# sit on other keys there). Their keycodes are the ZMK ones, written as qwerty
# keycodes for an OS set to dvorak (hyprland.lua), so e.g. S-minus is "{{" and
# S-z is ":" exactly as on the ZMK boards. Keys a layer leaves out fall through to
# [main], so the left home row mods still work on NAV (ctrl+shift+arrows).
# The ZMK layers' outer keys (esc, tab and caps positions) are not ported.
#
# Not ported: holding both shifts turning on caps word. The top row has mods too, in
# a different order from the home row, so shortcuts like gui+ctrl+h can be done with
# one hand.

[ids]
17ef:616a

[global]
oneshot_timeout = {QUICK_TAP_MS}

[main]
# top row, then home row
""")
for k, m in MODS.items():
    w(f"{k} = overloadt({m}, oneshotk(qt_{k}, {k}), {T[m]})")
w("""
# Thumb layers. Space is ZMK's lt_spc: a tap within 150ms of another key is just a
# space (require-prior-idle), otherwise hold 175ms for NUM. Capslock is a plain
# layer-tap (150ms) for NAV; tapped it is still caps lock.
space = overloadi(space, overloadt(num, space, 175), 150)
capslock = overloadt(nav, capslock, 150)

# ZMK NUM_LAYER. The mod-taps keep their mods on hold, so ctrl+1 and friends work.
[num]""")
for k, m in MODS.items():
    tap = f"oneshotk(qtn_{k}, {NUM_TAP[k]})" if k in NUM_QT else NUM_TAP[k]
    w(f"{k} = overloadt({m}, {tap}, {T[m]})")
for k, v in NUM_PLAIN:
    w(f"{k} = {v}")
w("\n# ZMK NAV_LAYER\n[nav]")
for k, v in NAV:
    w(f"{k} = {v}")
w("\n# Quick-tap layers, one per mod-tap key (see the header)")
for k in MODS:
    w(f"\n[qt_{k}]\n{k} = {k}")
for k in NUM_QT:
    w(f"\n[qtn_{k}]\n{k} = {NUM_TAP[k]}")
print("\n".join(out))
